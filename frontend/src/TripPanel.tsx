import { ReactNode, useCallback, useEffect, useState } from "react";

export type Detail = {
  id: number; title: string; event: string; place: string | null; status: string; source: string;
  start_date: string; end_date: string; generated_start_date: string | null; generated_end_date: string | null;
  notes: string | null; cancel_reason: string | null; plan_year: number; plan_status: string; updated_at: string;
  editable: boolean;
  participants: { person_id: number; name: string; role: string; travels: boolean; position: string }[];
  combined: { id: number; event: string }[];
};
type Hist = {
  id: number; changed_at: string; change_type: string; category: string | null; reason: string | null;
  before_data: Record<string, unknown> | null; after_data: Record<string, unknown> | null; changed_by: string;
};
type Warning = { level: string; code: string; message: string };
type Impact = {
  blocked: boolean; requires_acknowledgement: boolean; new_warnings: Warning[]; resolved_warnings: number;
};
type Person = { person_id: number; name: string; position: string };

const CATEGORIES: Record<string, string> = {
  business_request: "Business request",
  company_event_conflict: "Conflict with a company event",
  merged: "Combined with another trip",
  capacity: "Capacity",
  budget: "Budget",
  other: "Other",
};
const CHANGE_LABEL: Record<string, string> = {
  created: "Added", generated: "Generated by the rules", moved: "Moved", resized: "Length changed",
  reassigned: "People changed", edited: "Edited", status: "Status changed", cancelled: "Cancelled",
  merged: "Combined", split: "Split",
};
const STATUS_LABEL: Record<string, string> = {
  generated: "Generated", planned: "Confirmed", requested: "Requested", approved: "Approved",
  completed: "Done", cancelled: "Cancelled",
};

export const fmtDates = (a: string, b: string) => {
  const f = (s: string) => new Date(s + "T00:00:00").toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" });
  return a === b ? f(a) : `${f(a)} to ${f(b)}`;
};
const fmtWhen = (iso: string) => new Date(iso).toLocaleString("en-US", { month: "short", day: "numeric", year: "numeric", hour: "numeric", minute: "2-digit" });

async function send(url: string, body: unknown): Promise<{ ok: boolean; status: number; data: Record<string, unknown> }> {
  const r = await fetch(url, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const data = (await r.json().catch(() => ({}))) as Record<string, unknown>;
  return { ok: r.ok, status: r.status, data };
}
const detailOf = (data: Record<string, unknown>) => (typeof data.detail === "string" ? data.detail : "The change could not be saved. Please try again.");

/** Shows what a change would do to the rules, live, and asks for acknowledgement when needed. */
function ImpactPanel({ url, body, ack, setAck, onResult }: {
  url: string; body: unknown | null; ack: boolean; setAck: (v: boolean) => void; onResult: (r: Impact | null) => void;
}) {
  const [state, setState] = useState<{ kind: "idle" | "loading" | "error"; text?: string } | { kind: "ok"; impact: Impact }>({ kind: "idle" });
  const key = JSON.stringify(body);
  useEffect(() => {
    setAck(false);
    if (body === null) { setState({ kind: "idle" }); onResult(null); return; }
    setState({ kind: "loading" });
    const timer = setTimeout(async () => {
      const r = await send(url, body);
      if (r.ok) { const impact = r.data as unknown as Impact; setState({ kind: "ok", impact }); onResult(impact); }
      else { setState({ kind: "error", text: detailOf(r.data) }); onResult(null); }
    }, 450);
    return () => clearTimeout(timer);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [key, url]);

  return (
    <div className="impact" aria-live="polite">
      <h4>Effect on the plan</h4>
      {state.kind === "idle" && <p className="muted">Change something to see how it affects the rules.</p>}
      {state.kind === "loading" && <p className="muted">Checking the rules…</p>}
      {state.kind === "error" && <p className="problem">{state.text}</p>}
      {state.kind === "ok" && (
        <>
          {state.impact.new_warnings.length === 0 && <p>This change breaks no rules.</p>}
          {state.impact.new_warnings.length > 0 && (
            <ul className="issues">
              {state.impact.new_warnings.map((w, i) => (
                <li key={i} className={w.level === "block" ? "error" : w.level === "warn" ? "warning" : "info"}>
                  <span className="badge">{w.level === "block" ? "not allowed" : w.level}</span> {w.message}
                </li>
              ))}
            </ul>
          )}
          {state.impact.resolved_warnings > 0 && (
            <p className="good">This change also resolves {state.impact.resolved_warnings} existing {state.impact.resolved_warnings === 1 ? "warning" : "warnings"}.</p>
          )}
          {state.impact.requires_acknowledgement && !state.impact.blocked && (
            <label className="check">
              <input type="checkbox" checked={ack} onChange={(e) => setAck(e.target.checked)} />
              I understand these warnings and want to continue.
            </label>
          )}
        </>
      )}
    </div>
  );
}

function ReasonFields({ reason, setReason, category, setCategory }: {
  reason: string; setReason: (v: string) => void; category: string; setCategory: (v: string) => void;
}) {
  return (
    <>
      <label>Reason for the change (required)
        <textarea rows={2} maxLength={500} value={reason} onChange={(e) => setReason(e.target.value)}
          placeholder="Everyone who sees this trip will see why it was changed." />
      </label>
      <label>Type of reason
        <select value={category} onChange={(e) => setCategory(e.target.value)}>
          {Object.entries(CATEGORIES).map(([k, l]) => <option key={k} value={k}>{l}</option>)}
        </select>
      </label>
    </>
  );
}

function PersonPicker({ onPick, exclude }: { onPick: (p: Person) => void; exclude: Set<number> }) {
  const [q, setQ] = useState("");
  const [found, setFound] = useState<Person[]>([]);
  useEffect(() => {
    if (q.trim().length < 2) { setFound([]); return; }
    const t = setTimeout(async () => {
      const r = await fetch(`/api/plan/people?q=${encodeURIComponent(q.trim())}`);
      if (r.ok) setFound((await r.json()) as Person[]);
    }, 300);
    return () => clearTimeout(t);
  }, [q]);
  return (
    <div className="picker">
      <label>Add a person
        <input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Type at least two letters of a name" />
      </label>
      {found.filter((p) => !exclude.has(p.person_id)).length > 0 && (
        <ul className="found">
          {found.filter((p) => !exclude.has(p.person_id)).map((p) => (
            <li key={p.person_id}>
              <button type="button" className="link" onClick={() => { onPick(p); setQ(""); setFound([]); }}>
                {p.name} · {p.position}
              </button>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

export function TripPanel({ id, onChanged, onClose }: { id: number; onChanged: () => void; onClose: () => void }) {
  const [d, setD] = useState<Detail | null>(null);
  const [hist, setHist] = useState<Hist[]>([]);
  const [mode, setMode] = useState<"view" | "edit" | "cancel">("view");
  const [msg, setMsg] = useState<{ text: string; ok: boolean } | null>(null);

  const load = useCallback(async () => {
    const [a, b] = await Promise.all([fetch(`/api/plan/trips/${id}`), fetch(`/api/plan/trips/${id}/history`)]);
    if (a.ok) setD((await a.json()) as Detail);
    if (b.ok) setHist((await b.json()) as Hist[]);
  }, [id]);
  useEffect(() => { setMode("view"); setMsg(null); void load(); }, [load]);

  if (!d) return <p>Loading…</p>;
  const changedDates = d.generated_start_date && (d.generated_start_date !== d.start_date || d.generated_end_date !== d.end_date);
  const status = async (to: "planned" | "completed") => {
    const r = await send(`/api/plan/trips/${id}/status`, { status: to, expected_updated_at: d.updated_at });
    if (!r.ok) return setMsg({ text: detailOf(r.data), ok: false });
    setMsg(null); await load(); onChanged();
  };
  const done = async (text: string) => { setMode("view"); setMsg({ text, ok: true }); await load(); onChanged(); };

  return (
    <div className="subform">
      <div className="head">
        <div>
          <h4>{d.title}</h4>
          <p className="muted">
            {fmtDates(d.start_date, d.end_date)} · {STATUS_LABEL[d.status] ?? d.status}
            {d.source === "manual" && " · Added by hand"}
            {d.plan_status === "published" && " · Plan is published: changes are marked"}
          </p>
        </div>
        <button className="link" onClick={onClose}>Close</button>
      </div>
      {changedDates && <p className="note">Planned by the rules for {fmtDates(d.generated_start_date!, d.generated_end_date!)}.</p>}
      {d.combined.length > 0 && <p className="note">Includes: {d.combined.map((c) => c.event).join(", ")}</p>}
      {d.cancel_reason && <p className="note">Cancelled: {d.cancel_reason}</p>}
      {d.notes && <p>{d.notes}</p>}
      <ul className="chips">
        {d.participants.map((p) => (
          <li key={p.person_id} className={p.role === "organizer" ? "chip strong" : "chip"}>
            {p.name} · {p.position}{p.role === "organizer" && " (organizer)"}{!p.travels && " (host)"}
          </li>
        ))}
      </ul>
      {msg && <p className={msg.ok ? "good" : "problem"} role={msg.ok ? "status" : "alert"}>{msg.text}</p>}

      {mode === "view" && d.editable && (
        <p className="row">
          <button onClick={() => setMode("edit")}>Change this trip</button>
          {d.status === "generated" && <button className="secondary" onClick={() => status("planned")}>Confirm</button>}
          {["planned", "requested", "approved"].includes(d.status) && <button className="secondary" onClick={() => status("completed")}>Mark as done</button>}
          <button className="link" onClick={() => setMode("cancel")}>Cancel this trip</button>
        </p>
      )}
      {mode === "edit" && <EditForm d={d} onCancel={() => setMode("view")} onDone={() => done("The change was saved.")} />}
      {mode === "cancel" && <CancelForm d={d} onCancel={() => setMode("view")} onDone={() => done("The trip was cancelled.")} />}

      <h4>History</h4>
      <ul className="hist">
        {hist.map((h) => {
          const b = h.before_data as { start?: string; end?: string } | null;
          const a = h.after_data as { start?: string; end?: string; after_publication?: boolean } | null;
          return (
            <li key={h.id}>
              <strong>{CHANGE_LABEL[h.change_type] ?? h.change_type}</strong>
              <span className="muted"> · {h.changed_by} · {fmtWhen(h.changed_at)}</span>
              {b?.start && a?.start && <div className="muted">{fmtDates(b.start, b.end ?? b.start)} → {fmtDates(a.start, a.end ?? a.start)}</div>}
              {h.reason && <div>{h.reason}{h.category && h.category !== "other" && <span className="muted"> ({CATEGORIES[h.category] ?? h.category})</span>}</div>}
              {a?.after_publication && <span className="badge">after publication</span>}
            </li>
          );
        })}
      </ul>
    </div>
  );
}

function SaveRow({ ok, why, busy, label, onSave, onCancel }: {
  ok: boolean; why: string | null; busy: boolean; label: string; onSave: () => void; onCancel: () => void;
}) {
  return (
    <>
      {!ok && why && <p className="muted">{why}</p>}
      <p className="row">
        <button type="button" disabled={!ok || busy} onClick={onSave}>{busy ? "Saving…" : label}</button>
        <button type="button" className="link" onClick={onCancel}>Cancel</button>
      </p>
    </>
  );
}

function EditForm({ d, onCancel, onDone }: { d: Detail; onCancel: () => void; onDone: () => void }) {
  const [start, setStart] = useState(d.start_date);
  const [end, setEnd] = useState(d.end_date);
  const [notes, setNotes] = useState(d.notes ?? "");
  const [removed, setRemoved] = useState<Set<number>>(new Set());
  const [added, setAdded] = useState<Person[]>([]);
  const [reason, setReason] = useState("");
  const [category, setCategory] = useState("business_request");
  const [ack, setAck] = useState(false);
  const [impact, setImpact] = useState<Impact | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const changed = start !== d.start_date || end !== d.end_date || notes !== (d.notes ?? "") || removed.size > 0 || added.length > 0;
  const base = {
    ...(start !== d.start_date || end !== d.end_date ? { start_date: start, end_date: end } : {}),
    ...(notes !== (d.notes ?? "") ? { notes } : {}),
    add_participants: added.map((p) => ({ person_id: p.person_id, role: "traveler", travels: true })),
    remove_participants: [...removed],
    reason: reason.trim() || "Preview",   // the preview needs a valid reason; saving requires a real one
    category,
    expected_updated_at: d.updated_at,
  };
  const reasonOk = reason.trim().length >= 3;
  const ready = changed && end >= start;
  const needAck = impact?.requires_acknowledgement && !impact.blocked;
  const ok = ready && reasonOk && !!impact && !impact.blocked && (!needAck || ack);
  const why = !changed ? "Change something first." : end < start ? "The end date cannot be before the start date."
    : !reasonOk ? "Enter a reason." : impact?.blocked ? "This change is not allowed." : needAck && !ack ? "Confirm that you understand the warnings." : null;

  const save = async () => {
    setBusy(true); setError(null);
    const r = await send(`/api/plan/trips/${d.id}/edit?commit=true`, { ...base, reason: reason.trim(), acknowledge: ack });
    setBusy(false);
    if (r.ok) onDone(); else setError(detailOf(r.data));
  };

  return (
    <div className="editbox">
      <div className="row">
        <label>From<input type="date" value={start} onChange={(e) => setStart(e.target.value)} /></label>
        <label>To<input type="date" value={end} min={start} onChange={(e) => setEnd(e.target.value)} /></label>
      </div>
      <label>Notes<textarea rows={2} maxLength={1000} value={notes} onChange={(e) => setNotes(e.target.value)} /></label>
      <fieldset>
        <legend>People</legend>
        <ul className="chips">
          {d.participants.map((p) => (
            <li key={p.person_id} className={removed.has(p.person_id) ? "chip gone" : "chip"}>
              {p.name}
              <button type="button" className="link" onClick={() => setRemoved((s) => { const n = new Set(s); if (n.has(p.person_id)) n.delete(p.person_id); else n.add(p.person_id); return n; })}>
                {removed.has(p.person_id) ? "Undo" : "Remove"}
              </button>
            </li>
          ))}
          {added.map((p) => (
            <li key={p.person_id} className="chip strong">
              {p.name} (new)
              <button type="button" className="link" onClick={() => setAdded((a) => a.filter((x) => x.person_id !== p.person_id))}>Undo</button>
            </li>
          ))}
        </ul>
        <PersonPicker exclude={new Set([...d.participants.map((p) => p.person_id), ...added.map((p) => p.person_id)])}
          onPick={(p) => setAdded((a) => [...a, p])} />
      </fieldset>
      <ReasonFields reason={reason} setReason={setReason} category={category} setCategory={setCategory} />
      <ImpactPanel url={`/api/plan/trips/${d.id}/edit?commit=false`} body={ready ? base : null} ack={ack} setAck={setAck} onResult={setImpact} />
      {error && <p className="problem" role="alert">{error}</p>}
      <SaveRow ok={ok} why={why} busy={busy} label="Save change" onSave={save} onCancel={onCancel} />
    </div>
  );
}

function CancelForm({ d, onCancel, onDone }: { d: Detail; onCancel: () => void; onDone: () => void }) {
  const [reason, setReason] = useState("");
  const [category, setCategory] = useState("business_request");
  const [ack, setAck] = useState(false);
  const [impact, setImpact] = useState<Impact | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const body = { reason: reason.trim() || "Preview", category, expected_updated_at: d.updated_at };
  const reasonOk = reason.trim().length >= 3;
  const needAck = impact?.requires_acknowledgement && !impact.blocked;
  const ok = reasonOk && !!impact && !impact.blocked && (!needAck || ack);
  const save = async () => {
    setBusy(true); setError(null);
    const r = await send(`/api/plan/trips/${d.id}/cancel?commit=true`, { ...body, reason: reason.trim(), acknowledge: ack });
    setBusy(false);
    if (r.ok) onDone(); else setError(detailOf(r.data));
  };
  return (
    <div className="editbox">
      <p>Cancelling removes the trip from the calendar. It stays in the history.</p>
      <ReasonFields reason={reason} setReason={setReason} category={category} setCategory={setCategory} />
      <ImpactPanel url={`/api/plan/trips/${d.id}/cancel?commit=false`} body={body} ack={ack} setAck={setAck} onResult={setImpact} />
      {error && <p className="problem" role="alert">{error}</p>}
      <SaveRow ok={ok} why={!reasonOk ? "Enter a reason." : needAck && !ack ? "Confirm that you understand the warnings." : null}
        busy={busy} label="Cancel the trip" onSave={save} onCancel={onCancel} />
    </div>
  );
}

type EventOpt = { id: number; name: string; active: boolean };
type Place = { id: number | null; kind: string; name: string };

export function AddTrip({ year, onDone, onCancel }: { year: number; onDone: (id: number) => void; onCancel: () => void }): ReactNode {
  const [events, setEvents] = useState<EventOpt[]>([]);
  const [places, setPlaces] = useState<Place[]>([]);
  const [eventId, setEventId] = useState<number | "">("");
  const [placeKey, setPlaceKey] = useState("");
  const [start, setStart] = useState(`${year}-01-05`);
  const [end, setEnd] = useState(`${year}-01-05`);
  const [notes, setNotes] = useState("");
  const [defaults, setDefaults] = useState(true);
  const [reason, setReason] = useState("");
  const [category, setCategory] = useState("business_request");
  const [ack, setAck] = useState(false);
  const [impact, setImpact] = useState<Impact | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    void fetch("/api/catalog").then(async (r) => r.ok && setEvents(((await r.json()) as { event_types: EventOpt[] }).event_types.filter((e) => e.active)));
    void fetch("/api/plan/places").then(async (r) => r.ok && setPlaces((await r.json()) as Place[]));
  }, []);

  const place = places.find((p) => `${p.kind}:${p.id}` === placeKey);
  const reasonOk = reason.trim().length >= 3;
  const ready = eventId !== "" && !!place && end >= start && start.startsWith(String(year));
  const body = ready ? {
    event_type_id: eventId, unit_id: place!.id, start_date: start, end_date: end, notes: notes || null,
    default_participants: defaults, reason: reason.trim() || "Preview", category,
  } : null;
  const needAck = impact?.requires_acknowledgement && !impact.blocked;
  const ok = ready && reasonOk && !!impact && !impact.blocked && (!needAck || ack);
  const kindLabel: Record<string, string> = { nationwide: "Nationwide", region: "Region", cluster: "Cluster", local_office: "Local office" };

  const save = async () => {
    setBusy(true); setError(null);
    const r = await send(`/api/plan/${year}/trips?commit=true`, { ...body, reason: reason.trim(), acknowledge: ack });
    setBusy(false);
    if (r.ok) onDone(((r.data.trip as Detail) ?? { id: 0 }).id); else setError(detailOf(r.data));
  };

  return (
    <section className="card">
      <h3>Add a trip</h3>
      <p className="muted">For a trip the rules did not plan. It counts toward the quotas, so the app tells you if it goes beyond them.</p>
      <div className="row">
        <label>Event type
          <select value={eventId} onChange={(e) => setEventId(e.target.value ? Number(e.target.value) : "")}>
            <option value="">Choose…</option>
            {events.map((e) => <option key={e.id} value={e.id}>{e.name}</option>)}
          </select></label>
        <label>Place
          <select value={placeKey} onChange={(e) => setPlaceKey(e.target.value)}>
            <option value="">Choose…</option>
            {places.map((p) => <option key={`${p.kind}:${p.id}`} value={`${p.kind}:${p.id}`}>{kindLabel[p.kind]}: {p.name}</option>)}
          </select></label>
      </div>
      <div className="row">
        <label>From<input type="date" value={start} onChange={(e) => { setStart(e.target.value); if (end < e.target.value) setEnd(e.target.value); }} /></label>
        <label>To<input type="date" value={end} min={start} onChange={(e) => setEnd(e.target.value)} /></label>
      </div>
      <label>Notes (optional)<textarea rows={2} maxLength={1000} value={notes} onChange={(e) => setNotes(e.target.value)} /></label>
      <label className="check"><input type="checkbox" checked={defaults} onChange={(e) => setDefaults(e.target.checked)} /> Add the usual people for this event and place</label>
      <ReasonFields reason={reason} setReason={setReason} category={category} setCategory={setCategory} />
      <ImpactPanel url={`/api/plan/${year}/trips?commit=false`} body={body} ack={ack} setAck={setAck} onResult={setImpact} />
      {error && <p className="problem" role="alert">{error}</p>}
      <SaveRow ok={ok} why={!ready ? "Choose an event type, a place and the dates." : !reasonOk ? "Enter a reason." : needAck && !ack ? "Confirm that you understand the warnings." : null}
        busy={busy} label="Add the trip" onSave={save} onCancel={onCancel} />
    </section>
  );
}
